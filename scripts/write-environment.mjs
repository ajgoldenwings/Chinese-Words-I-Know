// Writes src/web/environments/environment.generated.ts from the CDK outputs file.
// Usage: node scripts/write-environment.mjs <cdk-outputs.json> <region> [outFile]
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const DEFAULT_OUT = 'src/web/environments/environment.generated.ts';

/** Finds an output value by key in any stack of the CDK outputs object. */
function findOutput(outputs, key) {
  for (const stack of Object.values(outputs)) {
    if (stack && typeof stack === 'object' && typeof stack[key] === 'string' && stack[key]) {
      return stack[key];
    }
  }
  throw new Error(`CDK outputs are missing "${key}".`);
}

/** Returns the TypeScript source for the generated environment file. */
export function buildEnvironmentSource(outputs, region) {
  if (!region) throw new Error('A region is required.');
  const values = {
    assetBaseUrl: '',
    apiUrl: findOutput(outputs, 'ApiUrl'),
    userPoolId: findOutput(outputs, 'UserPoolId'),
    userPoolClientId: findOutput(outputs, 'UserPoolClientId'),
    region,
  };
  return (
    '// Generated by scripts/write-environment.mjs in CI. Do not edit.\n' +
    `export const environment = ${JSON.stringify(values, null, 2)};\n`
  );
}

export function writeEnvironment(outputsPath, region, outFile = DEFAULT_OUT) {
  const outputs = JSON.parse(readFileSync(outputsPath, 'utf8'));
  writeFileSync(outFile, buildEnvironmentSource(outputs, region));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const [outputsPath, region, outFile] = process.argv.slice(2);
  if (!outputsPath || !region) {
    console.error('Usage: node scripts/write-environment.mjs <cdk-outputs.json> <region> [outFile]');
    process.exit(1);
  }
  writeEnvironment(outputsPath, region, outFile);
}
